def build_benchmark_item(
    seed: Seed,
    sample_index: int,
    *,
    long_form: bool = True,
    benchmark_version: str = "v1",
) -> BenchmarkItem:
    """Deterministically expand one Seed into one BenchmarkItem.

    ``long_form=False`` selects the short-form difficulty targets and drops
    the explicit word-count sentence from the rendered instruction (see
    ``_DIFFICULTY_TARGETS_SHORT_FORM`` and ``_build_instruction``) -- for the
    verifier-evaluation project phase, where long-form length is no longer a
    goal. Default is unchanged so the original long-form benchmark
    (``data/benchmark/benchmark_v1.jsonl``) stays byte-for-byte reproducible.
    """
    domain = seed.domain.value if hasattr(seed.domain, "value") else str(seed.domain)
    difficulty = seed.difficulty_hint.value if hasattr(seed.difficulty_hint, "value") else str(seed.difficulty_hint)
    doc_type = seed.document_type_hint

    content_builder = _DOMAIN_CONTENT_BUILDERS[domain]
    all_sections, all_components = content_builder(seed)

    targets = (_DIFFICULTY_TARGETS if long_form else _DIFFICULTY_TARGETS_SHORT_FORM)[difficulty]
    body_count = (_DIFFICULTY_BODY_COUNT if long_form else _DIFFICULTY_BODY_COUNT_SHORT_FORM)[difficulty]
    component_count = _DIFFICULTY_COMPONENT_COUNT[difficulty]

    body_sections = all_sections[:body_count]
    words_per_section = max(150, targets["min_words"] // (body_count + 2))

    section_id_prefix = f"{seed.subdomain}"
    intro_id = "introduction"
    summary_id = "summary"

    required_sections: List[RequiredSection] = [
        RequiredSection(
            section_id=intro_id,
            title="Introduction",
            purpose=f"Motivate {seed.topic} and outline the structure of this document.",
            required_points=[
                f"State why {seed.topic.lower()} matters within {seed.subdomain.replace('_', ' ')}.",
                "Outline the structure of the remaining sections.",
            ],
            target_words=words_per_section,
        )
    ]
    slot_id_by_index: Dict[int, str] = {}
    for idx, slot in enumerate(body_sections):
        section_id = slot["suffix"]
        slot_id_by_index[idx] = section_id
        required_sections.append(
            RequiredSection(
                section_id=section_id,
                title=slot["title"],
                purpose=slot["purpose"],
                required_points=list(slot["points"]),
                target_words=words_per_section,
            )
        )
    required_sections.append(
        RequiredSection(
            section_id=summary_id,
            title="Summary",
            purpose=f"Synthesize the document and restate the central conclusions about {seed.topic}.",
            required_points=[
                "Restate the central definition, framework, or result established earlier.",
                "Reference the key result and, if present, the limitations discussed earlier.",
            ],
            target_words=words_per_section,
        )
    )

    # Components
    component_slots = all_components[:component_count]
    component_id_by_index: Dict[int, str] = {}
    required_components: List[RequiredComponent] = []
    for idx, comp in enumerate(component_slots):
        component_id = comp["suffix"]
        component_id_by_index[idx] = component_id
        depends_on: List[str] = []
        dep_idx = comp.get("depends_on_index")
        if dep_idx is not None and dep_idx in component_id_by_index:
            depends_on = [component_id_by_index[dep_idx]]
        placement_section = slot_id_by_index.get(comp["body_slot_index"], intro_id)
        required_components.append(
            RequiredComponent(
                component_id=component_id,
                type=comp["type"],
                required=True,
                placement=placement_section,
                description=comp["description"],
                reference_required=comp.get("reference_required", False),
                depends_on=depends_on,
            )
        )

    # Terminology / notation constraints
    term_count = _DIFFICULTY_TERM_COUNT[difficulty]
    key_concepts = list(seed.key_concepts) or [seed.subtopic]
    terminology_constraints = [
        TerminologyConstraint(canonical_term=term, allowed_variants=[], forbidden_variants=[])
        for term in key_concepts[:term_count]
    ]

    notation_count = _DIFFICULTY_NOTATION_COUNT[difficulty]
    notation_constraints = [
        NotationConstraint(symbol=sym, meaning=f"as used for {seed.subtopic} in this document", scope="global", must_be_defined=True)
        for sym in list(seed.candidate_notation)[:notation_count]
    ]

    # Hard constraints
    hard_constraints: List[HardConstraint] = []
    term_list_str = ", ".join(c.canonical_term for c in terminology_constraints)
    hard_constraints.append(
        HardConstraint(
            constraint_id="terminology_consistency",
            type="terminology_consistency",
            description=f"Use the terms {term_list_str} consistently throughout every section and table; do not substitute synonyms.",
            severity="hard",
            applicable_to=["all_sections", "tables", "summary"],
        )
    )
    if notation_constraints:
        notation_list_str = ", ".join(c.symbol for c in notation_constraints)
        hard_constraints.append(
            HardConstraint(
                constraint_id="notation_consistency",
                type="notation_consistency",
                description=f"Use {notation_list_str} consistently for the same objects throughout; do not introduce alternate notation for the same object.",
                severity="hard",
                applicable_to=["equations", "all_sections", "summary"],
            )
        )
    if difficulty in ("intermediate", "advanced", "extreme") and len(required_sections) >= 3:
        hard_constraints.append(
            HardConstraint(
                constraint_id="structural_ordering",
                type="structural_ordering",
                description=f"Define or establish the material in \"{required_sections[1].title}\" before it is used in any later section.",
                severity="hard",
                applicable_to=["all_sections"],
            )
        )
    if domain in ("scientific_engineering", "financial_economic") and difficulty in ("intermediate", "advanced", "extreme"):
        categories_source = key_concepts[:4]
        if categories_source:
            hard_constraints.append(
                HardConstraint(
                    constraint_id="category_consistency",
                    type="category_consistency",
                    description=(
                        f"Use the exact categories {', '.join(categories_source)} in the same order in every "
                        "section and table that references them."
                    ),
                    severity="hard",
                    applicable_to=["all_sections", "tables", "summary"],
                )
            )
    if domain == "financial_economic":
        hard_constraints.append(
            HardConstraint(
                constraint_id="hypothetical_labeling",
                type="hypothetical_labeling",
                description=(
                    "Clearly label all numerical examples as hypothetical, never invent company-specific real "
                    "figures, and distinguish percentage changes from percentage-point changes."
                ),
                severity="hard",
                applicable_to=["all_sections", "tables"],
            )
        )

    # Cross-section dependencies. Body slot index 1 (the second required_sections
    # entry after "Introduction") is always the domain's "core definition/setup"
    # section -- see e.g. _math_content's "formal_definition" at index 1.
    cross_section_dependencies: List[CrossSectionDependency] = []
    core_definition_section_id = slot_id_by_index.get(1, intro_id)
    core_definition_title = next(
        (s.title for s in required_sections if s.section_id == core_definition_section_id),
        required_sections[0].title,
    )
    worked_examples_id = slot_id_by_index.get(2, summary_id)
    cross_section_dependencies.append(
        CrossSectionDependency(
            dependency_id="reuse_core_definition",
            source_section=core_definition_section_id,
            target_sections=[worked_examples_id, summary_id],
            relation="must_reuse",
            description=(
                f"Later sections, including the summary, must explicitly reuse the material introduced in "
                f"the \"{core_definition_title}\" section."
            ),
        )
    )
    if body_count >= 4:
        theorem_section_id = slot_id_by_index[3]
        theorem_section_title = body_sections[3]["title"]
        cross_section_dependencies.append(
            CrossSectionDependency(
                dependency_id="reference_key_result",
                source_section=theorem_section_id,
                target_sections=[summary_id],
                relation="must_reference",
                description=f"The \"{theorem_section_title}\" section's result must be explicitly referenced in the Summary.",
            )
        )
    if body_count >= 8:
        limitations_section_id = slot_id_by_index[7]
        limitations_section_title = body_sections[7]["title"]
        cross_section_dependencies.append(
            CrossSectionDependency(
                dependency_id="limitations_consistent_with_scope",
                source_section=limitations_section_id,
                target_sections=[summary_id],
                relation="must_be_consistent_with",
                description=(
                    f"The conclusions in the Summary must remain consistent with the scope stated in "
                    f"\"{limitations_section_title}\"."
                ),
            )
        )

    # Layout / evaluation contract / forbidden content
    component_types = {c.type.value for c in required_components}
    numbered_theorems = bool(component_types & {"theorem", "lemma", "proposition", "corollary"})
    numbered_equations = bool(component_types & {"equation", "aligned_equations"}) or difficulty != "basic"
    callout_types = sorted(component_types & {"definition", "theorem", "risk_callout", "callout", "summary_box", "boxed_result"})

    layout_requirements = LayoutRequirements(
        table_of_contents=True,
        numbered_sections=True,
        numbered_equations=numbered_equations,
        numbered_theorems=numbered_theorems,
        required_callout_types=callout_types,
        preferred_layout_profile=DOMAIN_LAYOUT_PROFILE[domain],
    )

    forbidden_content = list(BASE_FORBIDDEN_CONTENT) + list(DOMAIN_EXTRA_FORBIDDEN.get(domain, []))

    evaluation_contract = EvaluationContract(
        required_section_coverage=True,
        required_component_coverage=True,
        cross_section_dependency_check=True,
        terminology_consistency_check=True,
        notation_consistency_check=bool(notation_constraints),
        latex_rendering_check=True,
        length_check=True,
    )

    target_length = TargetLength(
        target_pages=targets["pages"],
        min_words=targets["min_words"],
        max_words=targets["max_words"],
        min_sections=max(len(required_sections) - 1, 1),
        max_sections=len(required_sections) + 2,
    )

    audience = DOMAIN_AUDIENCE[domain]
    document_purpose = DOMAIN_PURPOSE_TEMPLATE[domain].format(topic=seed.topic)
    doc_type_human = doc_type.value.replace("_", " ") if hasattr(doc_type, "value") else str(doc_type).replace("_", " ")
    overview = (
        f"A {difficulty}-level {doc_type_human} that explains {seed.topic} for {audience}, covering "
        f"{', '.join(key_concepts[:3])}. {document_purpose} The document must be a compile-ready LaTeX "
        f"document with consistent notation and explicit cross-references between sections."
    )

    domain_code = DOMAIN_CODE[domain]
    sample_id = f"{domain_code}_{seed.subdomain}_{sample_index:04d}"

    source_provenance = [
        SourceProvenanceEntry(
            source_id=seed.source.source_id,
            usage="topic and structural seed only; instruction text is an original transformation",
            copied_text=False,
        )
    ]

    natural_language_instruction = _build_instruction(
        title=seed.topic,
        doc_type_human=doc_type_human,
        audience=audience,
        document_purpose=document_purpose,
        target_length=target_length,
        required_sections=required_sections,
        required_components=required_components,
        hard_constraints=hard_constraints,
        cross_section_dependencies=cross_section_dependencies,
        numbered_theorems=numbered_theorems,
        long_form=long_form,
    )

    return BenchmarkItem(
        sample_id=sample_id,
        benchmark_version=benchmark_version,
        domain=domain,
        subdomain=seed.subdomain,
        document_type=doc_type,
        difficulty=difficulty,
        title=seed.topic,
        overview=overview,
        audience=audience,
        document_purpose=document_purpose,
        target_length=target_length,
        required_sections=required_sections,
        required_components=required_components,
        hard_constraints=hard_constraints,
        cross_section_dependencies=cross_section_dependencies,
        terminology_constraints=terminology_constraints,
        notation_constraints=notation_constraints,
        layout_requirements=layout_requirements,
        forbidden_content=forbidden_content,
        evaluation_contract=evaluation_contract,
        natural_language_instruction=natural_language_instruction,
        source_provenance=source_provenance,
    )


def _build_instruction(
    *,
    title: str,
    doc_type_human: str,
    audience: str,
    document_purpose: str,
    target_length: TargetLength,
    required_sections: List[RequiredSection],
    required_components: List[RequiredComponent],
    hard_constraints: List[HardConstraint],
    cross_section_dependencies: List[CrossSectionDependency],
    numbered_theorems: bool,
    long_form: bool = True,
) -> str:
    """Assemble the natural-language instruction from the same structured
    fields used elsewhere in the item, so every hard constraint, section
    title, and component type is guaranteed (by construction) to appear as
    text -- this is what validators.py's instruction-coverage check verifies.

    ``long_form=False`` omits the explicit word-/page-count directive --
    the document's brevity comes from the (shorter) required_sections list
    passed in, not from an instruction telling the model how long to write.
    """
    parts: List[str] = []

    if long_form:
        parts.append(
            f"Write a {target_length.min_words}- to {target_length.max_words}-word "
            f"(approximately {target_length.target_pages}-page) compile-ready LaTeX {doc_type_human} "
            f"titled \"{title}\" for {audience}. {document_purpose}"
        )
    else:
        parts.append(
            f"Write a concise, compile-ready LaTeX {doc_type_human} "
            f"titled \"{title}\" for {audience}. {document_purpose}"
        )

    section_list = "; ".join(f"{i + 1}. {s.title}" for i, s in enumerate(required_sections))
    parts.append(f"Structure the document with the following sections, in order: {section_list}.")

    guidance_sentences = []
    for s in required_sections:
        purpose = s.purpose[0].lower() + s.purpose[1:] if s.purpose else ""
        guidance_sentences.append(f"In the \"{s.title}\" section, {purpose}")
    parts.append(" ".join(guidance_sentences))

    component_list = "; ".join(
        f"a {c.type.value.replace('_', ' ')} ({c.description})" for c in required_components
    )
    parts.append(f"Include the following required LaTeX elements: {component_list}.")

    if hard_constraints:
        parts.append("Follow these constraints exactly: " + " ".join(hc.description for hc in hard_constraints))

    if cross_section_dependencies:
        parts.append(" ".join(d.description for d in cross_section_dependencies))

    numbering_clause = "numbered sections" + (", numbered theorems," if numbered_theorems else "") + " and numbered equations with cross-references where appropriate"
    parts.append(
        f"Use {numbering_clause}. Do not invent citations, do not include raw markdown code fences, "
        "and do not add agent commentary."
    )

    return " ".join(parts)


def build_items_for_domain(
    seeds: List[Seed],
    *,
    long_form: bool = True,
    benchmark_version: str = "v1",
) -> List[BenchmarkItem]:
    """Build one BenchmarkItem per seed, numbering sample_ids 1..N in order."""
    return [
        build_benchmark_item(seed, index, long_form=long_form, benchmark_version=benchmark_version)
        for index, seed in enumerate(seeds, start=1)
    ]
