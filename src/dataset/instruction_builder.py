def _pick_type(candidates: Sequence[str], preferred: Sequence[str], fallback: str) -> str:
    for pref in preferred:
        if pref in candidates:
            return pref
    return fallback


_TITLE_CASE_MINOR_WORDS = {"of", "and", "the", "vs", "in", "for", "to", "a", "an"}


def _title_case(text: str) -> str:
    """Title-case a phrase without mangling acronyms (WACC) or capitalizing
    connector words (Cost of Debt, not Cost Of Debt) -- plain str.title() does both.
    """
    words = text.split()
    out = []
    for i, word in enumerate(words):
        if word.isupper() and len(word) > 1:
            out.append(word)
        elif i > 0 and word.lower() in _TITLE_CASE_MINOR_WORDS:
            out.append(word.lower())
        else:
            out.append(word[:1].upper() + word[1:])
    return " ".join(out)


