class ManualSeedAdapter(SourceAdapter):
    """The primary Stage-1 source: a curated, hand-authored seed bank."""

    source_type = SourceType.MANUAL_CURATION.value

    def __init__(self, registry: SourceRegistry) -> None:
        self._registry = registry

    def _curriculum_source_ref(self, domain: str) -> SeedSourceRef:
        source_id = f"curriculum_{domain}"
        record = SourceRecord(
            source_id=source_id,
            source_type=SourceType.STANDARD_CURRICULUM,
            source_title=f"Standard curriculum topic taxonomy ({domain})",
            source_url=None,
            publisher_or_owner="Manually curated by the dataset author",
            edition_or_version="v1",
            access_date=date.today().isoformat(),
            license_name="Standard curriculum (no copyrighted prose reused)",
            license_url=None,
            allowed_use="topic, subtopic, and learning-objective seeding",
            attribution_text=f"Topic seed based on {_CURRICULUM_ATTRIBUTION[domain]}.",
            extraction_method=ExtractionMethod.MANUAL,
            copied_text_flag=False,
            manual_review_required=False,
            notes=["Contains no reused prose from any copyrighted textbook, paper, or filing."],
        )
        self._registry.register(record)
        return SeedSourceRef(
            source_id=record.source_id,
            source_title=record.source_title,
            source_url=record.source_url,
            license_name=record.license_name,
            access_date=record.access_date,
        )

    def fetch_seeds_for_domain(self, domain: str, limit: int) -> List[Seed]:
        """Return the curated seed bank for a whole domain (all subdomains)."""
        raw_seeds = _DOMAIN_SEED_BANKS.get(domain, [])
        if not raw_seeds:
            logger.warning("No manual seeds defined for domain %r.", domain)
            return []
        source_ref = self._curriculum_source_ref(domain)
        seeds = [
            self._to_seed(domain, source_ref, raw, index)
            for index, raw in enumerate(raw_seeds[:limit], start=1)
        ]
        return seeds

    def fetch_seeds(self, subdomain: str, limit: int) -> List[Seed]:
        """SourceAdapter-interface entry point: filter the curated bank by subdomain."""
        for domain, raw_seeds in _DOMAIN_SEED_BANKS.items():
            matches = [raw for raw in raw_seeds if raw.subdomain == subdomain]
            if matches:
                source_ref = self._curriculum_source_ref(domain)
                return [
                    self._to_seed(domain, source_ref, raw, index)
                    for index, raw in enumerate(matches[:limit], start=1)
                ]
        return []

    @staticmethod
    def _to_seed(domain: str, source_ref: SeedSourceRef, raw: _RawSeed, index: int) -> Seed:
        seed_id = f"seed_{domain}_{raw.subdomain}_{index:03d}"
        return Seed(
            seed_id=seed_id,
            domain=domain,
            subdomain=raw.subdomain,
            source=source_ref,
            topic=raw.topic,
            subtopic=raw.subtopic,
            source_headings=[raw.topic, raw.subtopic],
            learning_objectives=list(raw.objectives),
            key_concepts=list(raw.concepts),
            prerequisites=list(raw.prerequisites),
            candidate_notation=list(raw.notation),
            candidate_equations=list(raw.equations),
            candidate_components=list(raw.components),
            source_notes=[
                f"Manually curated topic seed based on {_CURRICULUM_ATTRIBUTION[domain]}; "
                "no copyrighted prose reused."
            ],
            difficulty_hint=raw.difficulty,
            document_type_hint=raw.doc_type,
        )


def seed_bank_size(domain: str) -> int:
    """Number of curated seeds available for a domain (used by balance.py)."""
    return len(_DOMAIN_SEED_BANKS.get(domain, []))
